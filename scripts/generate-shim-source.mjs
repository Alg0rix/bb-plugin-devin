#!/usr/bin/env node
// Regenerates lib/acp-stdio-shim-source.ts from lib/acp-stdio-shim.mjs so the
// host bundle can materialize the shim on machines that do not have the
// server's plugin checkout. test/host-launch-spec.test.ts fails on drift.
import { readFileSync, writeFileSync } from "node:fs";

const shim = readFileSync(new URL("../lib/acp-stdio-shim.mjs", import.meta.url), "utf8");
const out = `// Generated by scripts/generate-shim-source.mjs from lib/acp-stdio-shim.mjs. Do not edit.
export const ACP_STDIO_SHIM_SOURCE: string = ${JSON.stringify(shim)};
`;
writeFileSync(new URL("../lib/acp-stdio-shim-source.ts", import.meta.url), out);
